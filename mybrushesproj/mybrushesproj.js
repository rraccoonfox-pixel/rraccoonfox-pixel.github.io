// keyPressed() запускается при нажатии клавиши.
// key хранит символ этой клавиши.
function keyPressed() {
    // Английская S сохраняет рисунок в PNG.
  if (key === 's') {
    saveCanvas('my-drawing', 'png');
  }

  // Если нажали 1:
  if (key === '1') {

    // Завершаем возможный старый штрих.
    // Новый начнётся при следующем нажатии мыши.
    drawingTapered = false;

    // Запоминаем выбранную кисть.
    choice = '1';
  }

  // Остальные блоки работают точно так же:
  // проверяют клавишу и запоминают выбор.

  if (key === '2') {
    drawingTapered = false;
    choice = '2';
  }

  if (key === '3') {
    drawingTapered = false;
    choice = '3';
  }

  if (key === '4') {
    drawingTapered = false;
    choice = '4';
  }

  if (key === '5') {
    drawingTapered = false;
    choice = '5';
  }

  if (key === '6') {
    drawingTapered = false;
    choice = '6';
  }

  if (key === '7') {
    drawingTapered = false;
    choice = '7';
  }

  if (key === '8') {
    drawingTapered = false;
    choice = '8';
  }

  if (key === '9') {
    drawingTapered = false;
    choice = '9';
  }

  if (key === '0') {
    drawingTapered = false;
    choice = '0';
  }

  // Очистка по маленькой английской x.
  if (key === 'x') {
    drawingTapered = false;

    // Снова закрашиваем весь холст фоном.
    background(250);
  }

  // То же для большой английской X.
  if (key === 'X') {
    drawingTapered = false;
    background(250);
  }
}


