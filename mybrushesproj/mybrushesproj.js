// let означает «создай место для хранения значения».
// Называем это место choice.
let choice = '1';

// Здесь будем хранить загруженную PNG-картинку,
//название brushImage мы придумали сами.
let brushImage;

// Первой кисти нужно запоминать путь мыши:
// где ты начала линию и куда потом двигалась.
// Для этого создаём список с названием points.
// Пока ты ничего не нарисовала, точек в нём нет.
// Поэтому справа стоят пустые скобки [].
// Во время рисования сюда будут добавляться точки:
// например (100, 200), затем (105, 203), затем (110, 207).
//программа строит штрих: тонкий в начале, толстый посередине, тонкий в конце.
let points = [];
// Здесь сохраним копию пикселей холста
let savedPixels;

// Здесь запоминаем, начат ли штрих первой кисти. false означает «нет». true означает «да».
// При запуске ещё не рисуем, поэтому false.
let drawingTapered = false;

// preload() — специальная функция p5.js.
// В этом проекте она загружает картинку до setup().
function preload() {

  // loadImage() читает файл картинки.
  // Имя внутри кавычек должно совпадать с настоящим именем файла.
  // = означает «загрузи картинку и сохрани её в brushImage».
  brushImage = loadImage('brushpainttext.png');
}

// setup() запускается один раз при старте.
// Здесь создаём рабочее место для рисования.
function setup() {
  // Создаём инструкцию и ставим её сверху страницы.
  let instructions = createP('Choose your brush: press 1–0.');
  instructions.position(10, 0);

  // Создаём холст и ставим ниже инструкции.
  let drawingCanvas = createCanvas(600, 600);
  drawingCanvas.position(10, 50);

  background(250);

  // Ставим кнопку ниже холста.
  let saveButton = createButton('Save image');
  saveButton.position(10, 665);

  saveButton.mousePressed(function() {
    saveCanvas('my-drawing', 'png');
  });
}
// draw() автоматически повторяется много раз в секунду.
function draw() {

  if (mouseIsPressed) {
    // === означает «проверь, одинаковые ли значения».
    //
    // Эта строка спрашивает:
    // «В choice сейчас записано '1'?»
    if (choice === '1') {

      // Продолжаем только начатый штрих.
      if (drawingTapered) {

        // Нам нужна последняя запомненная точка,
        // чтобы сравнить её с новым положением мыши.
        //
        // points.length — сколько точек в списке.
        //
        // Номера элементов начинаются с 0:
        // у трёх точек номера 0, 1, 2.
        //
        // Поэтому номер последней точки:
        // количество точек минус 1.
        let lastPoint = points[points.length - 1];

        // mouseX и mouseY — координаты мыши сейчас.
        //
        // lastPoint.x и lastPoint.y —
        // координаты последней сохранённой точки.
        //
        // dist() измеряет расстояние между ними.
        //
        // Если мышь передвинулась больше чем
        // на 2 пикселя, сохраняем новую точку.
        //
        // Это не даёт записывать одинаковые точки,
        // когда мышь почти не двигается.
        if (dist(mouseX, mouseY, lastPoint.x, lastPoint.y) > 2) {

          // Создаём одну запись с двумя координатами:
          // x — горизонталь, y — вертикаль.
          //
          // points.push() добавляет эту запись
          // в конец списка.
          //
          // Старые точки остаются на своих местах.
          points.push( {
          x:
          mouseX, y:
            mouseY
          }
          );

          // Запускаем команды, которые рисуют
          // линию по сохранённым точкам.
          taperedBrush();
        }
      }
    }

    // Если выбрана 2 — запускаем голубую текстуру.
    if (choice === '2') {
      blueTextureBrush();
    }

    // Если выбрана 3 — запускаем штриховку.
    if (choice === '3') {
      hatching();
    }

    // Если выбрана 4 — запускаем цепочку.
    if (choice === '4') {
      chainBrush();
    }

    if (choice === '5') {

      // Сначала выбираем серый цвет.
      //
      // Два числа в stroke():
      // 40 — оттенок серого,
      // 70 — непрозрачность из 255.
      stroke(40, 70);

      // Затем рисуем карандашные царапинки.
      scratchBrush();
    }

    if (choice === '6') {

      // Здесь четыре числа:
      // красный, зелёный, синий, непрозрачность.
      //
      // Много красного, мало зелёного и синего:
      // получается красная кисть.
      stroke(210, 20, 35, 90);

      // Форма такая же, как у серой кисти.
      // Поэтому запускаем ту же функцию.
      scratchBrush();
    }

    if (choice === '7') {
      sprayPaint();
    }

    if (choice === '8') {
      greenTextureBrush();
    }

    if (choice === '9') {
      purpleBrush();
    }

    if (choice === '0') {
      rainbowSquares();
    }
  }
}


// КОГДА НАЖИМАЕМ МЫШЬ

// mousePressed() запускается один раз
// в момент нажатия кнопки мыши.
//
// draw() повторяется во время удержания,
// а mousePressed() отмечает начало нажатия.
function mousePressed() {

  if (choice === '1') {

    // Считываем пиксели текущего рисунка.
    loadPixels();

    // slice() создаёт отдельную копию списка.
    //
    // Теперь в savedPixels лежит рисунок,
    // который был ДО нового штриха.
    savedPixels = pixels.slice();

    // Начинается новый штрих.
    // Точки прошлого штриха больше не нужны.
    //
    // Очищаем только список координат.
    // Старый рисунок на холсте не удаляется.
    points = [];

    // Запоминаем место первого нажатия мыши.
    // Это первая точка нового штриха.
    points.push( {
    x:
    mouseX, y:
      mouseY
    }
    );

    // Сообщаем программе:
    // «штрих начался, можно его продолжать».
    drawingTapered = true;
  }
}


// mouseReleased() запускается при отпускании мыши.
function mouseReleased() {

  // Сообщаем: этот штрих закончен.
  drawingTapered = false;
}


// КИСТЬ 1: ТОНКО — ТОЛСТО — ТОНКО

// Это описание того, КАК рисует первая кисть.
// Само название функции ничего не рисует.
// Рисование начинается, когда вызываем taperedBrush().
function taperedBrush() {

  // Возвращаем холст к состоянию до текущего штриха.
  //
  // Зачем?
  // Сейчас заново нарисуем весь текущий штрих
  // с пересчитанной толщиной.
  //
  // Если не убрать его предыдущую версию,
  // старые толстые части останутся под новой линией.
  pixels.set(savedPixels);
  updatePixels();

  // Выбираем почти чёрный цвет.
  stroke(35);

  // Концы маленьких отрезков будут округлыми.
  // Так они лучше соединяются в одну линию.
  strokeCap(ROUND);

  // Соединяем точки по очереди.
  //
  // Начинаем с i = 1, то есть со второй точки:
  // её уже можно соединить с первой.
  //
  // i++ означает «увеличивай i на 1».
  for (let i = 1; i < points.length; i++) {

    // Вычисляем место отрезка внутри всего штриха.
    //
    // Около 0 — начало.
    // Около 0.5 — середина.
    // Около 1 — конец.
    //
    // Вычитаем 0.5, чтобы взять середину отрезка,
    // а не его край.
    let progress = (i - 0.5) / (points.length - 1);

    // sin() помогает плавно менять толщину.
    //
    // В начале и конце результат близок к 0.
    // В середине — к 1.
    //
    // Умножение на 6 даёт утолщение середины.
    // 0.5 оставляет небольшую толщину у концов.
    //
    // PI — готовое число π, примерно 3.14.
    let thickness = 0.5 + sin(progress * PI) * 6;

    // Устанавливаем вычисленную толщину.
    strokeWeight(thickness);

    // line() получает четыре координаты:
    // начало X, начало Y, конец X, конец Y.
    //
    // points[i - 1] — предыдущая точка.
    // points[i] — текущая точка.
    //
    // .x и .y достают координаты из записи.
    line(
      points[i - 1].x,
      points[i - 1].y,
      points[i].x,
      points[i].y
      );
  }
}


// КИСТЬ 2: ГОЛУБАЯ PNG-ТЕКСТУРА

function blueTextureBrush() {

  // Выбираем ширину отпечатка.
  // Изменишь 50 на 25 — он станет вдвое уже.
  let brushWidth = 50;

  // Вычисляем высоту по пропорциям картинки.
  //
  // Например, если картинка вдвое шире своей высоты,
  // при ширине 50 высота получится 25.
  //
  // Так изображение не растягивается.
  let brushHeight =
    brushWidth * brushImage.height / brushImage.width;

  // 255 оставляет цвет картинки прежним.
  // 20 делает каждый отпечаток прозрачным.
  //
  // Пока держишь мышь, отпечатки накладываются.
  // Поэтому цвет постепенно становится насыщеннее.
  tint(255, 20);

  // image() рисует картинку.
  //
  // Аргументы:
  // картинка, положение X, положение Y, ширина, высота.
  //
  // По умолчанию положение задаёт верхний левый угол.
  // Вычитаем половину ширины и высоты,
  // чтобы центр картинки оказался под мышью.
  image(
    brushImage,
    mouseX - brushWidth / 2,
    mouseY - brushHeight / 2,
    brushWidth,
    brushHeight
    );

  // Отключаем настройку прозрачности картинки.
  noTint();
}


// КИСТЬ 3: ОРАНЖЕВАЯ ШТРИХОВКА

function hatching() {

  // Цвет штрихов: тёмно-оранжевый.
  // Последнее число — непрозрачность.
  stroke(200, 65, 15, 140);

  // Толщина одного штриха.
  strokeWeight(1);

  // pmouseX и pmouseY — положение мыши
  // на предыдущем кадре.
  //
  // Вычитание показывает, насколько она сдвинулась.
  //
  // abs() убирает минус:
  // abs(-5) и abs(5) оба дают 5.
  //
  // Складываем движения по горизонтали и вертикали.
  // Получаем меру движения за кадр.
  let speed =
    abs(mouseX - pmouseX) + abs(mouseY - pmouseY);

  // Если мышь стоит, новые штрихи не добавляем.
  if (speed > 0) {

    // Вектор можно представить как стрелку:
    // у неё есть направление и длина.
    //
    // Здесь движение по Y ставим на место X,
    // а движение по X — на место Y.
    //
    // Это задаёт направление линий штриховки,
    // как в присланном тобой примере.
    let vector = createVector(
      mouseY - pmouseY,
      mouseX - pmouseX
      );

    // Скорость влияет на длину штрихов.
    //
    // constrain(значение, минимум, максимум)
    // не даёт результату выйти за пределы.
    //
    // Получаем длину от 2 до 15.
    let length = constrain(speed / 2, 2, 15);

    // Меняем длину стрелки, сохраняя направление.
    vector.setMag(length);

    // Между двумя положениями мыши добавим 3 штриха.
    let lerps = 3;

    for (let i = 0; i < lerps; i++) {

      // lerp() находит промежуточное положение.
      //
      // Например:
      // lerp(100, 200, 0.5) даст 150.
      //
      // Так штрихи появляются между положениями мыши,
      // а не только в одной текущей точке.
      let x = lerp(mouseX, pmouseX, i / lerps);
      let y = lerp(mouseY, pmouseY, i / lerps);

      // От точки x, y откладываем вектор
      // в одну сторону и в другую.
      //
      // Между полученными концами рисуем линию.
      line(
        x - vector.x,
        y - vector.y,
        x + vector.x,
        y + vector.y
        );
    }
  }
}


// КИСТЬ 4: ЦЕПОЧКА

function chainBrush() {

  // У овалов будет только контур.
  // Внутри они не закрашиваются.
  noFill();

  stroke(65, 40, 85, 150);
  strokeWeight(1);

  // Измеряем, насколько передвинулась мышь.
  let distance = dist(
    mouseX, mouseY,
    pmouseX, pmouseY
    );

  // Если мышь не двигалась, овал не добавляем.
  if (distance > 0) {

    // atan2() вычисляет угол движения.
    //
    // Например, движение вправо даст один угол,
    // движение вниз — другой.
    //
    // Это нужно, чтобы звено поворачивалось
    // вслед за твоей рукой.
    let angle = atan2(
      mouseY - pmouseY,
      mouseX - pmouseX
      );

    // Сохраняем настройки и положение координат.
    // После рисования вернём их через pop().
    push();

    // Временно переносим точку 0, 0 под курсор.
    translate(mouseX, mouseY);

    // Поворачиваем систему координат.
    rotate(angle);

    // Рисуем овал в новом центре 0, 0.
    // Ширина 10, высота 5.
    ellipse(0, 0, 10, 5);

    // Отменяем перенос и поворот.
    // Остальные кисти не будут повёрнуты.
    pop();
  }
}


// КИСТИ 5 И 6: КАРАНДАШНЫЕ ЦАРАПИНКИ

// Эти кисти различаются цветом,
// но рисуют одинаковые пять линий.
//
// Поэтому описание формы у них общее.
function scratchBrush() {

  // Каждая линия толщиной 1 пиксель.
  strokeWeight(1);

  // Повторяем команды внутри цикла пять раз.
  //
  // i по очереди становится:
  // 0, 1, 2, 3, 4.
  //
  // Когда i станет 5, условие i < 5
  // перестанет выполняться, и цикл закончится.
  for (let i = 0; i < 5; i++) {

    // Размещаем линии через 2 пикселя.
    //
    // Если mouseX = 100:
    // при i = 0 получим x = 100;
    // при i = 1 получим x = 102;
    // при i = 2 получим x = 104.
    let x = mouseX + i * 2;

    // Немного сдвигаем каждую линию вверх или вниз.
    //
    // random(-2, 2) каждый раз выбирает
    // случайное число от -2 до 2.
    let y = mouseY + random(-2, 2);

    // Выбираем случайную длину царапинки.
    let length = random(6, 12);

    // Начало линии: x, y.
    //
    // Конец:
    // немного левее или правее начала,
    // ниже начала на выбранную длину.
    //
    // Поэтому линии короткие, почти вертикальные,
    // но не идеально одинаковые.
    line(x, y, x + random(-1, 1), y + length);
  }
}


// КИСТЬ 7: УГОЛЬНОЕ НАПЫЛЕНИЕ

function sprayPaint() {

  // Тёмный цвет и непрозрачность 85 из 255.
  // Точки видны, но их можно дополнительно наслаивать.
  stroke(15, 15, 15, 160);

  // Размер каждой точки.
  strokeWeight(1);

  // Измеряем движение мыши за кадр.
  let speed =
    abs(mouseX - pmouseX) + abs(mouseY - pmouseY);

  // Даже неподвижная кисть имеет радиус 8 пикселей.
  let minRadius = 8;

  // В одной группе будет 12 случайных точек.
  // Больше число — гуще напыление.
  let sprayDensity = 12;

  // Рисуем 3 группы за кадр.
  // Получается 3 × 12 = 36 точек.
  let lerps = 3;

  // При быстром движении распыление расширяется.
  // Но радиус не выходит за пределы 8–20.
  let r = constrain(minRadius + speed / 4, 8, 20);

  // Это радиус в квадрате.
  // Нужен ниже для расчёта точек внутри круга.
  let rSquared = r * r;

  // Этот цикл размещает три группы
  // вдоль последнего движения мыши.
  for (let i = 0; i < lerps; i++) {

    let lerpX = lerp(mouseX, pmouseX, i / lerps);
    let lerpY = lerp(mouseY, pmouseY, i / lerps);

    // Для каждой группы создаём 12 точек.
    // j — отдельный счётчик внутреннего цикла.
    for (let j = 0; j < sprayDensity; j++) {

      // Случайное смещение влево или вправо
      // от центра группы.
      let randX = random(-r, r);

      // Для выбранного X находим допустимое
      // смещение вверх или вниз.
      //
      // sqrt() вычисляет квадратный корень.
      // Формула не даёт точке выйти за границу круга.
      let randY =
        random(-1, 1) * sqrt(rSquared - randX * randX);

      // Рисуем точку:
      // положение группы + случайное смещение.
      point(
        lerpX + randX,
        lerpY + randY
        );
    }
  }

  // Эта функция вызывается снова каждый кадр.
  // Поэтому при удержании мыши появляются новые точки,
  // и участок постепенно темнеет.
}


// КИСТЬ 8: ЗЕЛЁНАЯ ТЕКСТУРА ИЗ КВАДРАТОВ

function greenTextureBrush() {

  // Сохраняем настройки перед этой кистью.
  push();

  // Квадраты будут без обводки.
  noStroke();

  // Зелёная полупрозрачная заливка.
  fill(45, 135, 75, 60);

  // Представь маленькую сетку вокруг мыши.
  //
  // Этот цикл выбирает столбцы:
  // x = -15, -12, -9 ... 12, 15.
  //
  // Отрицательные X — левее мыши,
  // положительные — правее.
  for (let x = -15; x <= 15; x += 3) {

    // Для каждого столбца перебираем строки.
    //
    // Отрицательные Y — выше мыши,
    // положительные — ниже.
    //
    // <= означает «меньше или равно».
    for (let y = -9; y <= 9; y += 3) {

      // Пока точки образуют прямоугольную сетку.
      // Но нам нужен овальный отпечаток.
      //
      // Эта формула проверяет положение точки:
      // результат меньше 1 — внутри овала.
      //
      // 15 — половина ширины овала,
      // 9 — половина высоты.
      let distance = (x / 15) * (x / 15)
        + (y / 9) * (y / 9);

      if (distance < 1) {

        // Не заполняем каждое место сетки.
        //
        // random(1) выбирает число от 0 до 1.
        // Если оно меньше 0.65, рисуем квадрат.
        //
        // Так примерно 65% мест будут заполнены,
        // а остальные останутся просветами.
        if (random(1) < 0.65) {

          // Рисуем квадрат размером 1.5 пикселя.
          //
          // mouseX + x и mouseY + y размещают его
          // возле курсора.
          //
          // random(-0.5, 0.5) слегка сдвигает его,
          // чтобы сетка не была слишком ровной.
          square(
            mouseX + x + random(-0.5, 0.5),
            mouseY + y + random(-0.5, 0.5),
            1.5
            );
        }
      }
    }
  }

  // Возвращаем настройки до push().
  pop();
}


// КИСТЬ 9: ФИОЛЕТОВЫЕ ЗНАКИ >

function purpleBrush() {

  // Выбираем цвет линии и её толщину.
  stroke(65, 25, 95, 90);
  strokeWeight(1);

  // Запоминаем координаты мыши под короткими именами,
  // чтобы дальше было проще читать команды.
  let x = mouseX;
  let y = mouseY;

  // Верхняя часть знака:
  // от точки левее и выше мыши
  // к точке правее мыши.
  line(x - 3, y - 5, x + 3, y);

  // Нижняя часть:
  // от той же правой вершины
  // к точке левее и ниже мыши.
  line(x + 3, y, x - 3, y + 5);
}


// КИСТЬ 0: РАДУЖНЫЕ КОНТУРНЫЕ КВАДРАТЫ

function rainbowSquares() {

  // Сохраняем настройки остальных кистей.
  push();

  // Обычно цвет задаётся через красный, зелёный и синий.
  //
  // Здесь используем HSB:
  // H — оттенок: какой именно цвет;
  // S — насыщенность: насколько цвет ярко выражен;
  // B — яркость: насколько он светлый.
  //
  // Последнее значение — непрозрачность.
  //
  // Задаём шкалы:
  // оттенок от 0 до 360,
  // остальные значения от 0 до 100.
  colorMode(HSB, 360, 100, 100, 100);

  // frameCount — количество кадров с запуска.
  // Оно постоянно увеличивается.
  //
  // * 2 ускоряет изменение оттенка.
  //
  // % означает «остаток от деления».
  // Благодаря % 360 число возвращается к началу:
  // например, 362 % 360 даст 2.
  //
  // Так цвета повторяются по кругу радуги.
  let hue = (frameCount * 2) % 360;

  // Оставляем середину квадрата незакрашенной.
  noFill();

  // Меняется только hue — оттенок.
  // Насыщенность 75, яркость 85, непрозрачность 60.
  stroke(hue, 75, 85, 60);

  // Тонкий контур.
  strokeWeight(0.8);

  // Измеряем расстояние между двумя положениями мыши.
  let distance = dist(
    mouseX, mouseY,
    pmouseX, pmouseY
    );

  // Добавляем квадрат только при движении.
  if (distance > 0) {

    // Складываем старую и новую координаты
    // и делим на 2 — получаем середину.
    //
    // Например: (100 + 120) / 2 = 110.
    let midX = (mouseX + pmouseX) / 2;
    let midY = (mouseY + pmouseY) / 2;

    // Движение влияет на размер квадрата.
    // Но размер остаётся между 4 и 10 пикселями.
    let size = constrain(distance, 4, 10);

    // square() рисует от верхнего левого угла.
    //
    // Вычитаем половину размера,
    // чтобы центр оказался в midX, midY.
    square(
      midX - size / 2,
      midY - size / 2,
      size
      );
  }

  // Возвращаем обычный цветовой режим.
  // Поэтому другие кисти не меняют свои цвета.
  pop();
}


